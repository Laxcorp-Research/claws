// container-env-actual.test.ts — PR-8a/B/B coverage for parseClawsEnvB64
// (the CLAWS_ENV_B64 → flat-map decoder for the "actual" side of reconciliation).
//
// parseClawsEnvB64 is pure + total (never throws), so no mocks/timers needed.
import { gzipSync } from "node:zlib"
import { describe, it, expect } from "vitest"
import {
  parseClawsEnvB64,
  parseClawsEnvGzB64,
  parseClawsEnvPayload,
  type RawContainerEnv,
} from "@/lib/openclaw/container-env-actual"

// Build a CLAWS_ENV_B64 the same way deployer.ts does: base64 of the .env text.
const b64 = (envText: string) => Buffer.from(envText, "utf8").toString("base64")
const gzB64 = (envText: string) => gzipSync(Buffer.from(envText, "utf8")).toString("base64")

describe("parseClawsEnvB64 (PR-8a/B/B)", () => {
  it("empty string input → {}", () => {
    expect(parseClawsEnvB64("")).toEqual({})
  })

  it("malformed base64 input → {} and never throws", () => {
    // All-symbol input has no base64-alphabet chars → empty decode → {}.
    expect(() => parseClawsEnvB64("@@@@####$$$$")).not.toThrow()
    expect(parseClawsEnvB64("@@@@####$$$$")).toEqual({})
  })

  it("tolerates a missing CLAWS_ENV_B64 (undefined) → {} (total-function contract)", () => {
    // The cron reads env.CLAWS_ENV_B64; an absent var arrives as undefined.
    // Buffer.from(undefined,'base64') throws — the try/catch turns it into {}.
    expect(() => parseClawsEnvB64(undefined as unknown as string)).not.toThrow()
    expect(parseClawsEnvB64(undefined as unknown as string)).toEqual({})
  })

  it("well-formed .env with ANTHROPIC_API_KEY → decoded map", () => {
    const env = "OPENCLAW_GATEWAY_TOKEN=tok\nANTHROPIC_API_KEY=sk-ant-abc123\n"
    expect(parseClawsEnvB64(b64(env))).toEqual({
      OPENCLAW_GATEWAY_TOKEN: "tok",
      ANTHROPIC_API_KEY: "sk-ant-abc123",
    })
  })

  it(".env with comments → comment lines ignored, other keys present", () => {
    const env = "# Generated by Claws\nANTHROPIC_API_KEY=sk-ant-x\n# trailing comment\nFOO=bar\n"
    const r = parseClawsEnvB64(b64(env))
    expect(r.ANTHROPIC_API_KEY).toBe("sk-ant-x")
    expect(r.FOO).toBe("bar")
    expect(Object.keys(r)).toHaveLength(2)
  })

  it(".env with single- and double-quoted values → quotes stripped (dotenv convention)", () => {
    const env = `DQ="double quoted value"\nSQ='single quoted value'\n`
    expect(parseClawsEnvB64(b64(env))).toEqual({
      DQ: "double quoted value",
      SQ: "single quoted value",
    })
  })

  it(".env with a double-quoted multiline value → newline preserved/joined", () => {
    const env = `MULTI="line1\nline2"\nNEXT=ok\n`
    const r = parseClawsEnvB64(b64(env))
    expect(r.MULTI).toBe("line1\nline2")
    expect(r.NEXT).toBe("ok")
  })

  it(".env with no ANTHROPIC_API_KEY → key absent (other providers preserved)", () => {
    const env = "OPENAI_API_KEY=sk-openai\nFOO=bar\n"
    const r = parseClawsEnvB64(b64(env))
    expect(r.ANTHROPIC_API_KEY).toBeUndefined()
    expect(r.OPENAI_API_KEY).toBe("sk-openai")
  })

  it(".env with duplicate ANTHROPIC_API_KEY → last wins (dotenv convention)", () => {
    const env = "ANTHROPIC_API_KEY=first-key\nANTHROPIC_API_KEY=second-key\n"
    expect(parseClawsEnvB64(b64(env)).ANTHROPIC_API_KEY).toBe("second-key")
  })

  it(".env with blank lines and surrounding whitespace → ignored/trimmed", () => {
    const env = "\n\n   \nANTHROPIC_API_KEY=sk-ant-y\n\n  FOO=bar  \n"
    const r = parseClawsEnvB64(b64(env))
    expect(r.ANTHROPIC_API_KEY).toBe("sk-ant-y")
    expect(r.FOO).toBe("bar")
  })

  it("real-world fixture (generator.ts shape) → round-trip integrity", () => {
    // Mirrors src/lib/openclaw/generator.ts:generateEnvFile output: header
    // comments, blank-line sections, gateway token, then provider keys.
    const generated = [
      "# Generated by Claws - do not edit manually",
      "# Workspace: cmpnvr35x0000vshq8vhoirc3",
      "# Generated: 2026-06-02T00:00:00.000Z",
      "",
      "OPENCLAW_GATEWAY_TOKEN=gateway-fixture",
      "",
      "ANTHROPIC_API_KEY=sk-ant-api03-realistic-Key_Value-09",
      "OPENAI_API_KEY=sk-openai-realistic",
      "",
    ].join("\n")
    const r = parseClawsEnvB64(Buffer.from(generated).toString("base64"))
    expect(r).toEqual({
      OPENCLAW_GATEWAY_TOKEN: "gateway-fixture",
      ANTHROPIC_API_KEY: "sk-ant-api03-realistic-Key_Value-09",
      OPENAI_API_KEY: "sk-openai-realistic",
    })
  })
})

describe("parseClawsEnvPayload (gzipped current format + legacy fallback)", () => {
  it("prefers CLAWS_ENV_GZ_B64 and decodes the gzipped .env payload", () => {
    const env = "ANTHROPIC_API_KEY=sk-ant-gz\nOPENCLAW_GATEWAY_TOKEN=tok\n"
    const r = parseClawsEnvPayload({
      CLAWS_ENV_GZ_B64: gzB64(env),
      CLAWS_ENV_B64: b64("ANTHROPIC_API_KEY=legacy-should-not-win\n"),
    } as unknown as RawContainerEnv)

    expect(r.ANTHROPIC_API_KEY).toBe("sk-ant-gz")
    expect(r.OPENCLAW_GATEWAY_TOKEN).toBe("tok")
  })

  it("falls back to legacy CLAWS_ENV_B64 for old running containers", () => {
    const r = parseClawsEnvPayload({
      CLAWS_ENV_B64: b64("ANTHROPIC_API_KEY=sk-ant-legacy\n"),
    } as unknown as RawContainerEnv)

    expect(r.ANTHROPIC_API_KEY).toBe("sk-ant-legacy")
  })

  it("malformed CLAWS_ENV_GZ_B64 yields {} and never throws", () => {
    expect(() => parseClawsEnvGzB64("@@@@####$$$$")).not.toThrow()
    expect(parseClawsEnvGzB64("@@@@####$$$$")).toEqual({})
  })
})

